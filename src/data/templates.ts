export const templateMap = new Map(templates.map((t) => [t.slug, t]));

export function getTemplate(slug: string): Template | undefined {
  return templateMap.get(slug);
}

export function getTemplates(slugs: string[]): Template[] {
  return slugs.map((slug) => templateMap.get(slug)).filter((t): t is Template => Boolean(t));
}
